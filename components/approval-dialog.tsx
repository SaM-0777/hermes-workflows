import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from "@/components/ui/alert-dialog";
import { AlertTriangle, Code2, ShieldAlert } from "lucide-react";

interface WorkflowApprovalDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onApprove: () => void;
}

export function WorkflowApprovalDialog({
  open,
  onOpenChange,
  onApprove,
}: WorkflowApprovalDialogProps) {
  const handleApprove = () => {
    onOpenChange(false);
    onApprove();
  };

  return (
    <AlertDialog open={open} onOpenChange={onOpenChange}>
      <AlertDialogContent className="w-max max-w-md">
        <AlertDialogHeader>
          <div className="mb-2 flex size-10 items-center justify-center rounded-lg bg-amber-500/10 text-amber-600">
            <AlertTriangle className="size-5" />
          </div>

          <AlertDialogTitle className="text-base">
            Review before running this workflow
          </AlertDialogTitle>

          <AlertDialogDescription className="text-sm leading-relaxed">
            This workflow will execute Python code generated by the Hermes
            agent. Agent-generated code may perform actions on your system or
            interact with external services.
          </AlertDialogDescription>
        </AlertDialogHeader>

        <div className="space-y-3 rounded-lg border bg-muted/40 p-3">
          <div className="flex items-start gap-3">
            <Code2 className="mt-0.5 size-4 shrink-0 text-muted-foreground" />
            <div className="space-y-1">
              <p className="text-sm font-medium">Review the generated code</p>
              <p className="text-xs leading-relaxed text-muted-foreground">
                Inspect the Python code in your workflow nodes and make sure you
                understand what will be executed.
              </p>
            </div>
          </div>

          <div className="flex items-start gap-3">
            <ShieldAlert className="mt-0.5 size-4 shrink-0 text-muted-foreground" />
            <div className="space-y-1">
              <p className="text-sm font-medium">Run only if you trust it</p>
              <p className="text-xs leading-relaxed text-muted-foreground">
                Continue only when you are comfortable with the code and the
                actions it may perform.
              </p>
            </div>
          </div>
        </div>

        <AlertDialogFooter>
          <AlertDialogCancel>Cancel</AlertDialogCancel>
          <AlertDialogAction onClick={handleApprove}>
            Approve and run
          </AlertDialogAction>
        </AlertDialogFooter>
      </AlertDialogContent>
    </AlertDialog>
  );
}
